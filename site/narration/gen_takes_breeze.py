"""Generate Breeze TTS 2 takes for the lines listed in a jobs file (made by assemble.py plan): the GPU voice via
Breeze-TTS-2.cpp (ggml + Vulkan, runs on the Radeon without ROCm; pc/README.md). Same contract as gen_takes.py: one float
WAV per take at take_path(line, take); takes are cached by line + model + settings + seed.

voice.json → model: {"engine": "breeze-tts-2", "cli": <path to breeze-cli>, "gguf": <path to the .gguf>,
                     "voice": <saved voice name, made once with `breeze-cli --save-voice` from the frozen reference>,
                     "reference": <wav path, relative to site/>, "reference_text": <its transcript>,
                     "cfg_scale": 1.0}

Runs `breeze-server.exe` (next to `cli`) once and keeps it up for every take instead of shelling out to `breeze-cli`
per take: the CLI reloads the whole GGUF from disk and re-encodes the reference clip on every single call, so the GPU
sits idle through that reload and only does ~1s of real work per take (docs/server.md; pc/README.md says a take should
be about a second). The server loads the model once and, for the ref-audio/ref-text path, caches the reference encode
by its content hash after the first call (docs/voices.md), so steady-state calls are request-response only. Same model,
same seeds/temperatures/cfg_scale, same reference clip and transcript as before: the audio this produces is the same,
only how it is produced has changed, so take_key() in common.py (which does not hash the transport) still reuses every
take already generated by the old CLI path. Runs in the evaluation environment (soundfile, numpy)."""
import json, os, subprocess, sys, time, uuid
import numpy as np, soundfile as sf
import urllib.error, urllib.request
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import VOICE, take_path, gpu_slot

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = VOICE["model"]
assert M.get("engine") == "breeze-tts-2", "voice.json model.engine is not breeze-tts-2"

jobs = json.load(open(sys.argv[1]))
todo = [(j["line"], t) for j in jobs if j.get("lang", "en") == "en" for t in j["takes"] if not os.path.exists(take_path(j["line"], t))]
print(f"{len(todo)} take(s) to generate", flush=True)
if not todo:
    sys.exit(0)

cli, gguf = os.path.expandvars(M["cli"]), os.path.expandvars(M["gguf"])  # "$BREEZE_CLI" in voice.json: no machine path in git
server_bin = os.path.join(os.path.dirname(cli), "breeze-server.exe")
PORT = int(os.environ.get("BREEZE_SERVER_PORT", 8137))
BASE = f"http://127.0.0.1:{PORT}"


def server_alive():
    try:
        with urllib.request.urlopen(f"{BASE}/health", timeout=2) as r:
            return r.status == 200
    except Exception:
        return False


def start_server():
    # --split-chars 0: every line here is already one short narration line (pace.max_words_per_line in voice.json),
    # never the "minutes in one pass" case the default splitting guards against, and splitting mid-line would change
    # the audio (a new reference-conditioned restart partway through) for no benefit.
    proc = subprocess.Popen([server_bin, gguf, "--port", str(PORT), "--split-chars", "0"],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(600):  # the GGUF load that used to repeat per take now happens once, budget 60s for it
        if server_alive():
            return proc
        if proc.poll() is not None:
            sys.exit(f"breeze-server exited during startup (code {proc.returncode})")
        time.sleep(0.1)
    proc.kill()
    sys.exit("breeze-server did not become ready within 60s")


owns_server = not server_alive()
server_proc = start_server() if owns_server else None

voice_id = M.get("voice")
ref_audio_bytes = ref_text = None
if not voice_id:
    with open(os.path.join(SITE, M["reference"]), "rb") as f:
        ref_audio_bytes = f.read()
    ref_text = M["reference_text"]


def multipart(fields, files):
    boundary = uuid.uuid4().hex
    parts = []
    for k, v in fields.items():
        parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'.encode())
    for k, filename, data in files:
        parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"; filename="{filename}"\r\n'
                      f'Content-Type: application/octet-stream\r\n\r\n'.encode() + data + b"\r\n")
    parts.append(f'--{boundary}--\r\n'.encode())
    return b"".join(parts), boundary


def generate(line, take):
    fields = {"text": line, "cfg_scale": str(M.get("cfg_scale", 1.0))}
    if "seed" in take:
        fields["seed"] = str(take["seed"])
    if "temperature" in take:
        fields["temperature"] = str(take["temperature"])
    files = []
    if voice_id:
        fields["voice_id"] = voice_id
    else:
        fields["ref_text"] = ref_text
        files.append(("ref_audio", "reference.wav", ref_audio_bytes))
    body, boundary = multipart(fields, files)
    req = urllib.request.Request(f"{BASE}/v1/audio/speech", data=body,
                                  headers={"Content-Type": f"multipart/form-data; boundary={boundary}"})
    with urllib.request.urlopen(req, timeout=120) as r:
        pcm = r.read()
    a = np.frombuffer(pcm, dtype="<i2").astype(np.float32) / 32768.0
    return a, 24000


try:
    for n, (line, take) in enumerate(todo, 1):
        t0 = time.time()
        path = take_path(line, take)
        with gpu_slot():
            try:
                a, sr = generate(line, take)
            except urllib.error.HTTPError as e:
                detail = e.read().decode(errors="replace")[-800:]
                if e.code == 409:  # "busy": another process (another narrate.sh) is mid-take on the shared server
                    print(f"breeze-server busy on {line[:60]!r}, skipping this take for now", flush=True)
                    continue
                sys.exit(f"breeze-server failed on {line[:60]!r}: {detail}")
            except (urllib.error.URLError, TimeoutError) as e:
                # mirrors the old CLI "wedged" handling: skip this one take, a later round asks for a fresh one
                print(f"breeze-server unreachable on {line[:60]!r} ({e}), skipping this take", flush=True)
                continue
        if a.size == 0:
            sys.exit(f"breeze-server returned no audio for {line[:60]!r}")
        tmp = path + ".tmp.wav"
        sf.write(tmp, a, sr)
        os.replace(tmp, path)
        print(f"[{n}/{len(todo)}] {len(a)/sr:.1f}s audio in {time.time()-t0:.1f}s: {line[:60]}", flush=True)
finally:
    # Leave a server this call started running for later rounds/topics to find via server_alive() and reuse —
    # killing it here is what made every round/topic (narrate.sh calls this script fresh each time) pay the ~60s
    # GGUF reload again, which is the GPU-idle/pausing pattern this was meant to avoid (narration-breeze-server-fix
    # memory). The owner's PC session stops it once, when the whole bulk run is done (pc/README.md section 4).
    pass

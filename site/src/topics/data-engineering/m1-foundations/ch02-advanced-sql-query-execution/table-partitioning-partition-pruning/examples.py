TOTAL_PARTITIONS = 60
PRUNING_OFF_BUFFERS = 300
PRUNING_OFF_TIME_MS = 3.633
PRUNING_ON_BUFFERS = 5
PRUNING_ON_TIME_MS = 0.146
PRUNING_BUFFER_RATIO_DISPLAY = 60
PRUNING_TIME_RATIO_DISPLAY = 25

RUNTIME_PRUNING_SUBPLANS_REMOVED = 59
RUNTIME_PRUNING_BUFFERS = 5
RUNTIME_PRUNING_TIME_MS = 0.224

PARTITIONED_PLANNING_TIME_MS = 3.875
PARTITIONED_PLANNING_BUFFERS = 791

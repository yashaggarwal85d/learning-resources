TOPIC_RANGE_END = 29


def check():
    assert RUNTIME_PRUNING_SUBPLANS_REMOVED == TOTAL_PARTITIONS - 1
    assert TOPIC_RANGE_END == TOPIC_RANGE_START + 6
    assert PG_VERSION_DISPLAY == 16.15

    buffer_ratio = PRUNING_OFF_BUFFERS / PRUNING_ON_BUFFERS
    assert abs(buffer_ratio - PRUNING_BUFFER_RATIO_DISPLAY) < 1
    time_ratio = PRUNING_OFF_TIME_MS / PRUNING_ON_TIME_MS
    assert abs(time_ratio - PRUNING_TIME_RATIO_DISPLAY) < 2

    planning_time_ratio = PARTITIONED_PLANNING_TIME_MS / FLAT_PLANNING_TIME_MS
    assert abs(planning_time_ratio - PLANNING_TIME_RATIO_DISPLAY) < 2
    planning_buffer_ratio = PARTITIONED_PLANNING_BUFFERS / FLAT_PLANNING_BUFFERS
    assert abs(planning_buffer_ratio - PLANNING_BUFFER_RATIO_DISPLAY) < 2

    drop_ratio = DELETE_FLAT_TIME_MS / DROP_PARTITION_TIME_MS
    assert abs(drop_ratio - DROP_VS_DELETE_RATIO_DISPLAY) < 2

    assert QUIZ_PARTITIONS_PRUNED == QUIZ_PARTITIONS_TOTAL - 1

    print("table-partitioning-partition-pruning examples: all numbers check out")


if __name__ == "__main__":
    check()

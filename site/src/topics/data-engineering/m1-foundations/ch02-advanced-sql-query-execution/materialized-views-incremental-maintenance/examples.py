FULL_REFRESH_BASELINE_MS = 973.776
FULL_REFRESH_AFTER_SMALL_CHANGE_MS = 993.897
INCREMENTAL_UPDATE_MS = 5.536
INCREMENTAL_RATIO_DISPLAY = 180

SELECT_BLOCKED_MS = 861.419
SELECT_CONCURRENT_MS = 4.671
CONCURRENT_RATIO_DISPLAY = 184

SMALL_CHANGE_ROWS = 10
BASE_TABLE_ROWS = 3_000_000

FULL_REFRESH_BASELINE_DISPLAY_MS = 974
FULL_REFRESH_AFTER_SMALL_CHANGE_DISPLAY_MS = 994
INCREMENTAL_UPDATE_DISPLAY_MS = 6
SELECT_BLOCKED_DISPLAY_MS = 861
SELECT_CONCURRENT_DISPLAY_MS = 5

SNOWFLAKE_TARGET_LAG_MINUTES_DISPLAY = 10

QUIZ_ROWS_CHANGED = 1
QUIZ_TOTAL_ROWS = 3_000_000


def check():
    # full refresh barely moves even though only a handful of rows changed
    assert abs(FULL_REFRESH_AFTER_SMALL_CHANGE_MS - FULL_REFRESH_BASELINE_MS) < 50

    incremental_ratio = FULL_REFRESH_AFTER_SMALL_CHANGE_MS / INCREMENTAL_UPDATE_MS
    assert abs(incremental_ratio - INCREMENTAL_RATIO_DISPLAY) < 2

    concurrent_ratio = SELECT_BLOCKED_MS / SELECT_CONCURRENT_MS
    assert abs(concurrent_ratio - CONCURRENT_RATIO_DISPLAY) < 2

    assert SMALL_CHANGE_ROWS < BASE_TABLE_ROWS
    assert QUIZ_ROWS_CHANGED < QUIZ_TOTAL_ROWS

    assert round(FULL_REFRESH_BASELINE_MS) == FULL_REFRESH_BASELINE_DISPLAY_MS
    assert round(FULL_REFRESH_AFTER_SMALL_CHANGE_MS) == FULL_REFRESH_AFTER_SMALL_CHANGE_DISPLAY_MS
    assert round(INCREMENTAL_UPDATE_MS) == INCREMENTAL_UPDATE_DISPLAY_MS
    assert round(SELECT_BLOCKED_MS) == SELECT_BLOCKED_DISPLAY_MS
    assert round(SELECT_CONCURRENT_MS) == SELECT_CONCURRENT_DISPLAY_MS

    print("materialized-views-incremental-maintenance examples: all numbers check out")


if __name__ == "__main__":
    check()

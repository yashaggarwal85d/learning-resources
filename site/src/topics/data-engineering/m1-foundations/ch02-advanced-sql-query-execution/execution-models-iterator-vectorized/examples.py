"""Measured directly on PostgreSQL 16.15 and DuckDB 2.0.0, on the same machine (see SOURCES.md).

Both engines compute over identical logical data: 20,000,000 rows generated by the same
deterministic, id-based formula (a = (id % 97) / 10.0, b = (id % 13) + 1, c = id % 1000),
never transferred between the two engines as a file. Query: SELECT c, SUM(a*b), AVG(a),
COUNT(*) FROM exec_demo WHERE a > 0.1 GROUP BY c ORDER BY c.
"""

ROWS = 20_000_000

# --- Correctness check: same query, same answer, before comparing speed ---
FILTERED_ROW_COUNT = 19_587_629
PG_FILTERED_SUM = 671_854_810.5000007
DUCKDB_FILTERED_SUM = 671_854_810.5000004

# --- PostgreSQL 16.15, single execution thread, JIT off (the "plain iterator" baseline) ---
PG_ITERATOR_RUNS_MS = [4210.137, 3956.844, 3985.218]
PG_ITERATOR_MS = PG_ITERATOR_RUNS_MS[1]  # 3956.844, the steady-state run used in the reel

# --- PostgreSQL 16.15, its own default settings on this 4-core machine (parallel + JIT) ---
PG_DEFAULT_RUNS_MS = [1438.229, 1730.269, 1519.423]
PG_DEFAULT_MS = PG_DEFAULT_RUNS_MS[2]  # 1519.423

# --- DuckDB 2.0.0, PRAGMA threads=1 (single-threaded vectorized baseline) ---
DUCKDB_1THREAD_RUNS_MS = [246.217, 240.726, 264.865]
DUCKDB_1THREAD_MS = DUCKDB_1THREAD_RUNS_MS[1]  # 240.726

# --- DuckDB 2.0.0, PRAGMA threads=4 (all cores on this machine) ---
DUCKDB_4THREAD_RUNS_MS = [85.807, 72.693, 73.080]
DUCKDB_4THREAD_MS = DUCKDB_4THREAD_RUNS_MS[1]  # 72.693

# --- X100 paper's own vector-size experiment (not re-measured here; see SOURCES.md) ---
X100_DEFAULT_VECTOR_SIZE = 1024
X100_OPTIMAL_VECTOR_SIZE = 1000
X100_GOOD_RANGE_LOW = 128
X100_GOOD_RANGE_HIGH = 8000

# --- DuckDB's own default vector size (DuckDB documentation; see SOURCES.md) ---
DUCKDB_VECTOR_SIZE = 2048

# --- Morsel-driven paper's own reported result (not re-measured here; see SOURCES.md) ---
MORSEL_PAPER_CORES = 32
MORSEL_PAPER_SPEEDUP = 30  # "an average speedup of over 30 with 32 cores"

# --- This topic's own measured parallel scaling ---
LOCAL_CORES = 4

# --- DuckDB's own EXPLAIN output for the test query (approximate row counts it prints per pipeline stage) ---
DUCKDB_EXPLAIN_SAMPLE_ROWS = 4_000_000

# --- Display ratios (rounded to 1 decimal place for the reel's wording; asserted against the real ratio below) ---
ITERATOR_VS_VECTORIZED_DISPLAY = 16.4  # PG_ITERATOR_MS / DUCKDB_1THREAD_MS
DEFAULT_VS_4THREAD_DISPLAY = 20.9  # PG_DEFAULT_MS / DUCKDB_4THREAD_MS
LOCAL_SPEEDUP_DISPLAY = 3.3  # DUCKDB_1THREAD_MS / DUCKDB_4THREAD_MS


def check():
    assert FILTERED_ROW_COUNT > 0
    assert abs(PG_FILTERED_SUM - DUCKDB_FILTERED_SUM) < 0.001, \
        "both engines must agree on the answer before their speed is worth comparing"

    assert PG_ITERATOR_MS > DUCKDB_1THREAD_MS, \
        "the single-threaded iterator baseline should be slower than the single-threaded vectorized one"
    iterator_vs_vectorized = PG_ITERATOR_MS / DUCKDB_1THREAD_MS
    assert 10 < iterator_vs_vectorized < 25, "the measured gap should be roughly an order of magnitude"
    assert abs(iterator_vs_vectorized - ITERATOR_VS_VECTORIZED_DISPLAY) < 0.05

    assert PG_DEFAULT_MS > DUCKDB_4THREAD_MS, \
        "even with its own best default settings, PostgreSQL should still be slower here"
    default_vs_4thread = PG_DEFAULT_MS / DUCKDB_4THREAD_MS
    assert abs(default_vs_4thread - DEFAULT_VS_4THREAD_DISPLAY) < 0.05

    assert DUCKDB_1THREAD_MS > DUCKDB_4THREAD_MS, \
        "DuckDB should scale down in time as more threads are given the same work"
    local_speedup = DUCKDB_1THREAD_MS / DUCKDB_4THREAD_MS
    assert 2.5 < local_speedup < 4, "scaling across 4 cores should be substantial but short of a perfect 4x"
    assert abs(local_speedup - LOCAL_SPEEDUP_DISPLAY) < 0.05

    assert X100_GOOD_RANGE_LOW < X100_OPTIMAL_VECTOR_SIZE < X100_GOOD_RANGE_HIGH

    print("execution-models-iterator-vectorized examples: all numbers check out")


if __name__ == "__main__":
    check()

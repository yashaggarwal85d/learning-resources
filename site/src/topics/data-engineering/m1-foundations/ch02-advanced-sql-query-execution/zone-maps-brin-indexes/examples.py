BRIN_INDEX_BYTES = 24_576
BTREE_INDEX_BYTES = 14_655_488
SIZE_RATIO_DISPLAY = 596
BRIN_SIZE_KB_DISPLAY = 24
BTREE_SIZE_MB_DISPLAY = 14

CORRELATED_BRIN_BUFFERS = 15
CORRELATED_BRIN_TIME_MS = 0.140
NO_INDEX_BUFFERS = 10_811
NO_INDEX_TIME_MS = 116.638
CORRELATED_BUFFER_RATIO_DISPLAY = 720
CORRELATED_TIME_RATIO_DISPLAY = 833

UNCORRELATED_BRIN_BUFFERS = 10_826
UNCORRELATED_BRIN_TIME_MS = 200.129
UNCORRELATED_NO_INDEX_BUFFERS = 10_811
UNCORRELATED_NO_INDEX_TIME_MS = 100.469
UNCORRELATED_LOSSY_BLOCKS = 10_811

QUIZ_BLOCK_RANGES = 500
QUIZ_RANGES_CONTAINING_MATCH = 1


def check():
    size_ratio = BTREE_INDEX_BYTES / BRIN_INDEX_BYTES
    assert abs(size_ratio - SIZE_RATIO_DISPLAY) < 2
    assert round(BRIN_INDEX_BYTES / 1024) == BRIN_SIZE_KB_DISPLAY
    assert round(BTREE_INDEX_BYTES / 1024 / 1024) == BTREE_SIZE_MB_DISPLAY

    buffer_ratio = NO_INDEX_BUFFERS / CORRELATED_BRIN_BUFFERS
    assert abs(buffer_ratio - CORRELATED_BUFFER_RATIO_DISPLAY) < 2
    time_ratio = NO_INDEX_TIME_MS / CORRELATED_BRIN_TIME_MS
    assert abs(time_ratio - CORRELATED_TIME_RATIO_DISPLAY) < 2

    # BRIN on an uncorrelated column touches essentially the whole table,
    # same order of magnitude as a full scan, and ends up slower from recheck overhead.
    assert abs(UNCORRELATED_BRIN_BUFFERS - UNCORRELATED_NO_INDEX_BUFFERS) < 50
    assert UNCORRELATED_BRIN_TIME_MS > UNCORRELATED_NO_INDEX_TIME_MS
    assert UNCORRELATED_LOSSY_BLOCKS == UNCORRELATED_NO_INDEX_BUFFERS

    assert QUIZ_RANGES_CONTAINING_MATCH < QUIZ_BLOCK_RANGES

    print("zone-maps-brin-indexes examples: all numbers check out")


if __name__ == "__main__":
    check()

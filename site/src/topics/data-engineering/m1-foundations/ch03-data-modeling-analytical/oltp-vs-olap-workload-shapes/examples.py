"""Every number in the "OLTP vs OLAP workload shapes" reel, measured on the existing PostgreSQL 16.15 sandbox
(database "shop", table "orders": 2,400,000 rows, 445 MB). See SOURCES.md, "Measured directly", for the exact
EXPLAIN ANALYZE output these constants come from."""

PG_VERSION_DISPLAY = 16.15

ORDERS_ROWS = 2_400_000
ORDERS_ROWS_MILLIONS_DISPLAY = 2.4

POINT_LOOKUP_BUFFERS = 7  # shared hit=3 read=4
POINT_LOOKUP_BUFFERS_DISPLAY = 7
POINT_LOOKUP_TIME_MS = 0.635
POINT_LOOKUP_TIME_MS_DISPLAY = 0.6

FULL_SCAN_BUFFERS = 46_484  # shared hit=1 read=46483
FULL_SCAN_BUFFERS_THOUSANDS_DISPLAY = 46
FULL_SCAN_TIME_MS = 479.426
FULL_SCAN_TIME_MS_DISPLAY = 479

BUFFER_RATIO_DISPLAY = 6_600

AVG_WIDTH_ORDER_ID = 8
AVG_WIDTH_STATUS = 8
AVG_WIDTH_EVENT_TIME = 4
AVG_WIDTH_AMOUNT = 6
AVG_WIDTH_TAGS = 18
AVG_WIDTH_CHANNEL = 4
ROW_WIDTH_TOTAL = AVG_WIDTH_ORDER_ID + AVG_WIDTH_STATUS + AVG_WIDTH_EVENT_TIME + AVG_WIDTH_AMOUNT + AVG_WIDTH_TAGS + AVG_WIDTH_CHANNEL

AMOUNT_SHARE_DISPLAY = 8  # "about an eighth"

COLUMNAR_EXAMPLE_COLUMNS_USED = 5
COLUMNAR_EXAMPLE_COLUMNS_TOTAL = 100
COLUMNAR_EXAMPLE_PERCENT_DISPLAY = 5


def check():
    assert ROW_WIDTH_TOTAL == 48
    buffer_ratio = FULL_SCAN_BUFFERS / POINT_LOOKUP_BUFFERS
    assert abs(buffer_ratio - BUFFER_RATIO_DISPLAY) < 50
    amount_share = ROW_WIDTH_TOTAL / AVG_WIDTH_AMOUNT
    assert abs(amount_share - AMOUNT_SHARE_DISPLAY) < 1
    assert round(COLUMNAR_EXAMPLE_COLUMNS_USED / COLUMNAR_EXAMPLE_COLUMNS_TOTAL * 100) == COLUMNAR_EXAMPLE_PERCENT_DISPLAY
    assert FULL_SCAN_TIME_MS > POINT_LOOKUP_TIME_MS
    assert round(ORDERS_ROWS / 1_000_000, 1) == ORDERS_ROWS_MILLIONS_DISPLAY
    assert POINT_LOOKUP_BUFFERS == POINT_LOOKUP_BUFFERS_DISPLAY
    assert round(POINT_LOOKUP_TIME_MS, 1) == POINT_LOOKUP_TIME_MS_DISPLAY
    assert round(FULL_SCAN_BUFFERS / 1_000) == FULL_SCAN_BUFFERS_THOUSANDS_DISPLAY
    assert round(FULL_SCAN_TIME_MS) == FULL_SCAN_TIME_MS_DISPLAY
    print("oltp-vs-olap-workload-shapes examples: all numbers check out")


if __name__ == "__main__":
    check()

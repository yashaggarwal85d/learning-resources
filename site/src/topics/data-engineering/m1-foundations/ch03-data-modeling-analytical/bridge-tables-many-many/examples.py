TRUE_ORDER_TOTAL = 70.00
PROMO_TAG_COUNT = 3

UNWEIGHTED_DOUBLE_COUNTED_SUM = TRUE_ORDER_TOTAL * PROMO_TAG_COUNT

WEIGHT_FALL_SALE = 0.5
WEIGHT_FREE_SHIP = 0.3
WEIGHT_LOYALTY = 0.2
WEIGHT_SUM = WEIGHT_FALL_SALE + WEIGHT_FREE_SHIP + WEIGHT_LOYALTY

WEIGHTED_CORRECT_SUM = TRUE_ORDER_TOTAL * WEIGHT_SUM

CATEGORY_COUNT = 4
BRIDGE_ROW_COUNT = 7
DEEPEST_PATH_DEPTH = 2
SHALLOWEST_LEAF_DEPTH = 0

CATEGORIES_UNDER_TOP_VIA_BRIDGE = 3
CATEGORIES_UNDER_TOP_VIA_RECURSIVE_CTE = 3


def check():
    assert UNWEIGHTED_DOUBLE_COUNTED_SUM == 210.00
    assert WEIGHT_SUM == 1.0
    assert round(WEIGHTED_CORRECT_SUM, 2) == TRUE_ORDER_TOTAL
    assert UNWEIGHTED_DOUBLE_COUNTED_SUM != TRUE_ORDER_TOTAL
    assert BRIDGE_ROW_COUNT == 7
    assert DEEPEST_PATH_DEPTH > SHALLOWEST_LEAF_DEPTH
    assert CATEGORIES_UNDER_TOP_VIA_BRIDGE == CATEGORIES_UNDER_TOP_VIA_RECURSIVE_CTE
    print("bridge-tables-many-many examples: all numbers check out")


if __name__ == "__main__":
    check()

ORDER_1_AMOUNT = 70.00
ORDER_2_AMOUNT = 75.00
TRUE_ORDER_TOTAL = 145.00

TICKET_1_MINUTES = 30
TICKET_2_MINUTES = 45
TICKET_3_MINUTES = 20
TRUE_TICKET_MINUTES_TOTAL = 95

ORDER_COUNT = 2
TICKET_COUNT = 3

FANNED_OUT_ROW_COUNT = ORDER_COUNT * TICKET_COUNT
FANNED_OUT_AMOUNT_SUM = TRUE_ORDER_TOTAL * TICKET_COUNT

AGGREGATE_FIRST_ORDER_TOTAL = TRUE_ORDER_TOTAL
AGGREGATE_FIRST_TICKET_TOTAL = TRUE_TICKET_MINUTES_TOTAL


def check():
    assert ORDER_1_AMOUNT + ORDER_2_AMOUNT == TRUE_ORDER_TOTAL
    assert TICKET_1_MINUTES + TICKET_2_MINUTES + TICKET_3_MINUTES == TRUE_TICKET_MINUTES_TOTAL
    assert FANNED_OUT_ROW_COUNT == 6
    assert FANNED_OUT_AMOUNT_SUM == 435.00
    assert FANNED_OUT_AMOUNT_SUM != TRUE_ORDER_TOTAL
    assert AGGREGATE_FIRST_ORDER_TOTAL == TRUE_ORDER_TOTAL
    assert AGGREGATE_FIRST_TICKET_TOTAL == TRUE_TICKET_MINUTES_TOTAL
    print("conformed-dimensions-drill-across examples: all numbers check out")


if __name__ == "__main__":
    check()
